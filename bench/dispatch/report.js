'use strict';
// Renders bench/dispatch/RESULTS.md from the raw results bench.js saved (bench/dispatch/results/) and
// the hand-written analysis of each parity difference (findings.json). Every number in RESULTS.md
// comes from the results; rerun this after any benchmark run instead of editing the file.
//
// Usage: node bench/dispatch/report.js [results_dir] [out_file]

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { summary } = require('../lib/stats');
const { compareCases, canonical } = require('./lib/parity');
const { RUNS, SUITES, SPIKE_SUITES, EXACT_SUITES } = require('./lib/matrix');

const FIXTURES = path.join(__dirname, 'fixtures');
/** Python run, its Node counterpart (same pin, same allowed-vehicles mode). */
const PAIRS = [['9.14', 'py-9.14', 'node-9.14-span'], ['9.15', 'py-9.15', 'node-9.15-removevalues']];
const PHASES = ['build', 'solve', 'read', 'total'];

function loadResults(dir) {
  const out = {};
  for (const run of RUNS) {
    for (const flavor of ['spike', 'exact']) {
      for (const suite of SUITES) {
        const file = path.join(dir, run.label, `${suite}-${flavor}.json`);
        if (fs.existsSync(file)) ((out[run.label] ||= {})[`${suite}-${flavor}`] = JSON.parse(fs.readFileSync(file, 'utf8')));
      }
    }
  }
  return out;
}

const get = (results, run, key) => results[run] && results[run][key];

const fmtMs = (ms) => (ms >= 100 ? ms.toFixed(0) : ms >= 10 ? ms.toFixed(1) : ms.toFixed(2));
const fmtRatio = (py, node) => (node > 0 ? `${(py / node).toFixed(2)}×` : 'n/a');
const esc = (s) => String(s).replace(/\|/g, '\\|');

function fixtureHashes() {
  if (!fs.existsSync(FIXTURES)) return [];
  return fs.readdirSync(FIXTURES).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const sha = crypto.createHash('sha256').update(fs.readFileSync(path.join(FIXTURES, f))).digest('hex');
    return `${f} ${sha.slice(0, 12)}`;
  });
}

// ---------------------------------------------------------------- setup
function setupSection(results) {
  const any = Object.values(results).flatMap((r) => Object.values(r));
  const py = any.find((r) => r.runtime === 'python');
  const node = any.find((r) => r.runtime === 'node');
  const meta = (any.find((r) => r.fixture_meta) || {}).fixture_meta || {};
  const pinned = [...new Set(any.map((r) => r.pinned_cpu).filter((c) => c !== null && c !== undefined))];
  const repeats = [...new Set(any.filter((r) => r.flavor === 'exact').map((r) => r.repeats))];
  const lines = [
    '## Setup', '',
    `- Machine: ${os.cpus()[0].model.trim()}, ${os.cpus().length} logical CPUs, ${os.type()} ${os.release()}.`,
    `- Runtimes: Node ${node ? node.node : 'n/a'}; Python ${py ? py.python : 'n/a'} (the spikes' own code, \`python -I -B\`).`,
    `- Latency runs pinned to CPU ${pinned.join(', ') || 'none'} with \`taskset\`; the spike-flavour concurrency suites`
      + ' (t2f, t4, t5, cpsat) run unpinned, since they measure threads, processes and the event loop.',
    `- Exact flavour: one untimed pass records every solution signature, then ${repeats.join('/') || 'n/a'} timed`
      + ' passes; every timed pass must reproduce its signatures.',
    `- Fixtures: caby-dispatch spikes revision ${meta.spikes_revision || 'n/a'}, generated by gen_instances.py on Python`
      + ` ${meta.python || 'n/a'} with ortools ${meta.ortools || 'n/a'} (${meta.note || ''}). SHA-256 prefixes:`
      + ` ${fixtureHashes().map((h) => `\`${h}\``).join(', ') || 'n/a'}.`,
    '',
    '| Run | Runtime | OR-Tools | Allowed vehicles |',
    '|---|---|---|---|',
  ];
  for (const run of RUNS) {
    const r = Object.values(results[run.label] || {})[0];
    if (!r) continue;
    const mode = r.mode === 'span' ? 'SetAllowedVehiclesForIndex' : 'VehicleVar().RemoveValues() (spike workaround)';
    lines.push(`| ${run.label} | ${r.runtime} | ${r.ortools} | ${mode} |`);
  }
  return lines;
}

// ---------------------------------------------------------------- parity
function exactParity(results) {
  const rows = [], mismatches = [];
  for (const suite of SUITES) {
    if (!EXACT_SUITES.has(suite)) continue;
    const perPin = PAIRS.map(([v, py, node]) => {
      const a = get(results, py, `${suite}-exact`), b = get(results, node, `${suite}-exact`);
      return [v, a && b ? compareCases(a.cases, b.cases) : null, a, b];
    });
    const workloads = [...new Set(perPin.flatMap(([, c]) => (c ? Object.keys(c) : [])))];
    for (const w of workloads) {
      const cells = perPin.map(([v, c, a, b]) => {
        const x = c && c[w];
        if (!x) return 'not run';
        for (const m of x.mismatches) mismatches.push({ pin: v, suite, workload: w, ...m });
        const unstable = [...a.unstable, ...b.unstable].filter((k) => k.startsWith(`${w}/`)).length;
        const extra = [x.guardHits && `${x.guardHits} guard`, unstable && `${unstable} unstable`, x.missing.length && `${x.missing.length} missing`]
          .filter(Boolean).join(', ');
        return `${x.match}/${x.cases}${x.mismatches.length ? ` (**${x.mismatches.length} differ**)` : ''}${extra ? ` (${extra})` : ''}`;
      });
      rows.push(`| ${suite} | ${esc(w)} | ${cells.join(' | ')} |`);
    }
  }
  return { rows, mismatches };
}

function spikeParity(results) {
  const rows = [], mismatches = [];
  for (const suite of SUITES) {
    if (!SPIKE_SUITES.has(suite)) continue;
    const perPin = PAIRS.map(([v, py, node]) => {
      const a = get(results, py, `${suite}-spike`), b = get(results, node, `${suite}-spike`);
      return [v, a && b ? compareCases(a.cases, b.cases) : null];
    });
    const groups = [...new Set(perPin.flatMap(([, c]) => (c ? Object.keys(c) : [])))];
    for (const g of groups) {
      const cells = perPin.map(([v, c]) => {
        const x = c && c[g];
        if (!x) return 'not run';
        for (const m of x.mismatches) mismatches.push({ pin: v, suite, workload: g, ...m });
        return `${x.match}/${x.cases}`;
      });
      rows.push(`| ${suite} | ${esc(g)} | ${cells.join(' | ')} |`);
    }
  }
  return { rows, mismatches };
}

/** Flattens a spike's metrics into [path, value] rows; `ms` sample arrays become p50 / p95 / p99. */
function flatten(obj, prefix = '') {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    const p = prefix ? `${prefix}.${k}` : k;
    if (k === 'ms' && Array.isArray(v)) {
      const s = summary(v);
      out.push([`${p} p50/p95/p99`, `${fmtMs(s.p50)} / ${fmtMs(s.p95)} / ${fmtMs(s.p99)}`]);
    } else if (v && typeof v === 'object' && !Array.isArray(v)) {
      out.push(...flatten(v, p));
    } else {
      out.push([p, typeof v === 'object' ? canonical(v) : String(v)]);
    }
  }
  return out;
}

function spikeMetrics(results) {
  const lines = [];
  const cols = PAIRS.flatMap(([, py, node]) => [py, node]);
  for (const suite of SUITES) {
    if (!SPIKE_SUITES.has(suite)) continue;
    const flat = cols.map((run) => {
      const r = get(results, run, `${suite}-spike`);
      return r ? new Map(flatten(r.metrics)) : null;
    });
    if (flat.every((f) => f === null)) continue;
    const keys = [...new Set(flat.flatMap((f) => (f ? [...f.keys()] : [])))];
    lines.push('', `#### ${suite}`, '', `| Metric | ${cols.join(' | ')} |`, `|---|${cols.map(() => '--:').join('|')}|`);
    for (const k of keys) lines.push(`| ${esc(k)} | ${flat.map((f) => esc(f && f.has(k) ? f.get(k) : '')).join(' | ')} |`);
  }
  return lines;
}

function findingsSection(mismatches, findings) {
  const lines = [];
  const explained = (m) => findings.find((f) => f.suite === m.suite && (f.workload === undefined || f.workload === m.workload)
    && (f.pins === undefined || f.pins.includes(m.pin)));
  const groups = new Map();
  for (const m of mismatches) {
    const key = `${m.pin}|${m.suite}|${m.workload}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(m);
  }
  for (const [key, ms] of groups) {
    const [pin, suite, workload] = key.split('|');
    const f = explained(ms[0]);
    lines.push(`- **${pin} ${suite} / ${workload}**: ${ms.length} case(s) differ (${ms.slice(0, 5).map((m) => `\`${m.id}\``).join(', ')}`
      + `${ms.length > 5 ? ', ...' : ''}). ${f ? `**${f.verdict}.** ${f.analysis}` : '**Not yet analysed.**'}`);
    const first = ms[0];
    lines.push(`  - e.g. \`${esc(first.id)}\`: Python \`${canonical(first.a).slice(0, 300)}\`; Node \`${canonical(first.b).slice(0, 300)}\``);
  }
  for (const f of findings.filter((x) => x.always)) lines.push(`- **${f.title}**: **${f.verdict}.** ${f.analysis}`);
  return lines;
}

// ---------------------------------------------------------------- latency
function latencyStats(result, workload) {
  const t = result && result.timings[workload];
  if (!t || !t.length) return null;
  const by = { build: t.map((x) => x[0]), solve: t.map((x) => x[1]), read: t.map((x) => x[2]), total: t.map((x) => x[0] + x[1] + x[2]) };
  return Object.fromEntries(PHASES.map((p) => [p, summary(by[p])]));
}

function latencySection(results) {
  const lines = [];
  for (const [v, pyRun, nodeRun] of PAIRS) {
    lines.push('', `### OR-Tools ${v}: ${pyRun} vs ${nodeRun}`, '',
      '| Suite | Workload | Phase | Python p50 / p95 / p99 ms | Node p50 / p95 / p99 ms | p50 ratio |', '|---|---|---|--:|--:|--:|');
    for (const suite of SUITES) {
      if (!EXACT_SUITES.has(suite)) continue;
      const py = get(results, pyRun, `${suite}-exact`), node = get(results, nodeRun, `${suite}-exact`);
      if (!py || !node) continue;
      for (const w of Object.keys(py.timings)) {
        const a = latencyStats(py, w), b = latencyStats(node, w);
        if (!a || !b) continue;
        const phases = a.solve.p50 === 0 && a.read.p50 === 0 ? ['total'] : PHASES;
        for (const p of phases) {
          const label = p === 'total' ? '**total**' : p;
          const cell = (s) => `${fmtMs(s.p50)} / ${fmtMs(s.p95)} / ${fmtMs(s.p99)}`;
          lines.push(`| ${suite} | ${esc(w)} (n=${a.total.n}/${b.total.n}) | ${label} | ${cell(a[p])} | ${cell(b[p])} | ${fmtRatio(a[p].p50, b[p].p50)} |`);
        }
      }
    }
  }
  return lines;
}

/** Node only: SetAllowedVehiclesForIndex vs the RemoveValues workaround, and 9.14 vs 9.15. */
function apiVersionSection(results) {
  const cols = ['node-9.14-span', 'node-9.14-removevalues', 'node-9.15-span', 'node-9.15-removevalues', 'py-9.14', 'py-9.15'];
  const lines = ['', `| Suite | Workload | ${cols.join(' | ')} |`, `|---|---|${cols.map(() => '--:').join('|')}|`];
  for (const suite of ['t1', 't2a', 't2b', 't2c', 't2d']) {
    const ws = new Set(cols.flatMap((c) => Object.keys((get(results, c, `${suite}-exact`) || { timings: {} }).timings)));
    for (const w of ws) {
      const cells = cols.map((c) => {
        const s = latencyStats(get(results, c, `${suite}-exact`), w);
        return s ? fmtMs(s.total.p50) : '';
      });
      lines.push(`| ${suite} | ${esc(w)} | ${cells.join(' | ')} |`);
    }
  }
  return lines;
}

function render(results, findings) {
  const exact = exactParity(results);
  const spike = spikeParity(results);
  const exactTotal = exact.rows.length;
  const pinHead = PAIRS.map(([v, py, node]) => `${v} (${py} vs ${node})`);
  return [
    '# caby-dispatch spikes: ortools-node vs Python', '',
    '<!-- Generated by bench/dispatch/report.js from bench/dispatch/results; do not edit by hand. -->', '',
    'The caby-dispatch OR-Tools spikes (rules, live latency, monthly placement, threads, determinism, rescue,',
    'CP-SAT) run as written in Python and as a line-for-line Node port, on identical JSON fixtures, for both',
    'OR-Tools pins. The **spike** flavour repeats each experiment with its time limits; the **exact** flavour',
    'swaps time limits for solution limits (or a search that stops at a local optimum) so both runtimes must',
    'return the same status, objective, routes and assignments, and times build / solve / read.', '',
    ...setupSection(results), '',
    '## Parity', '',
    `### Exact flavour: identical results required (${exactTotal} workloads)`, '',
    'Cells: matching cases / cases. "guard": GUIDED_LOCAL_SEARCH ran out of new solutions before its solution',
    'limit and stopped at the guard time limit; those cases still compare, but are left out of the latency tables.', '',
    `| Suite | Workload | ${pinHead.join(' | ')} |`, `|---|---|${PAIRS.map(() => '--:').join('|')}|`,
    ...exact.rows, '',
    '### Spike flavour: per-case agreement under time limits', '',
    'Time-limited searches are not reproducible run to run, so these runs are compared on their accept',
    'counts, violations and objective distributions (next table); the per-case agreement is informative.', '',
    `| Suite | Experiment | ${pinHead.join(' | ')} |`, `|---|---|${PAIRS.map(() => '--:').join('|')}|`,
    ...spike.rows, '',
    '### Spike metrics, side by side', ...spikeMetrics(results), '',
    '### Differences and their causes', '',
    ...findingsSection(exact.mismatches, findings.filter((f) => f.flavor !== 'spike')),
    ...(exact.mismatches.length ? [] : ['- Exact flavour: no differences.']), '',
    `Spike flavour: ${spike.mismatches.length} per-case difference(s) under time limits.`,
    ...findingsSection([], findings.filter((f) => f.flavor === 'spike')), '',
    '## Latency (exact flavour, pinned)', '',
    'Build = model construction (and the warm-start assignment), solve = the solve call, read = walking the',
    'routes. Ratio = Python / Node (above 1: Node is faster). Node solves with the async API (libuv threadpool).',
    ...latencySection(results), '',
    '### Allowed-vehicles API cost vs version cost (total p50 ms)', '',
    'span = SetAllowedVehiclesForIndex; removevalues = the spike\'s VehicleVar().RemoveValues() workaround,',
    'which Python 9.15 must use (google/or-tools#5415).',
    ...apiVersionSection(results), '',
  ].join('\n');
}

function writeReport(dir = path.join(__dirname, 'results'), out = path.join(__dirname, 'RESULTS.md')) {
  const findingsFile = path.join(__dirname, 'findings.json');
  const findings = fs.existsSync(findingsFile) ? JSON.parse(fs.readFileSync(findingsFile, 'utf8')) : [];
  fs.writeFileSync(out, render(loadResults(dir), findings));
  process.stderr.write(`wrote ${out}\n`);
}

if (require.main === module) writeReport(process.argv[2], process.argv[3]);

module.exports = { flatten, latencyStats, render, loadResults, writeReport };
